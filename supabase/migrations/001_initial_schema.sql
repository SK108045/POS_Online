-- ==============================================================================
-- Oraforge Online POS - Initial Supabase Database Schema
-- Run this script in your Supabase SQL Editor to set up or upgrade the POS tables.
-- ==============================================================================

-- 1. Shop Settings Table
CREATE TABLE IF NOT EXISTS shop_settings (
    shop_id TEXT PRIMARY KEY DEFAULT 'retail',
    business_name TEXT NOT NULL DEFAULT 'BuildMart Hardware',
    business_type TEXT NOT NULL DEFAULT 'hardware',
    kra_pin TEXT DEFAULT '',
    address TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    receipt_footer TEXT DEFAULT 'Thank you for your business!\n------- END OF RECEIPT -------',
    tax_rate NUMERIC DEFAULT 0,
    tax_rate_confirmed BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Categories Table
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    sort_order INTEGER DEFAULT 0,
    business_type TEXT DEFAULT 'hardware',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE categories ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
ALTER TABLE categories ADD COLUMN IF NOT EXISTS business_type TEXT DEFAULT 'hardware';
ALTER TABLE categories ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_categories_shop ON categories (shop_id);

-- 3. Suppliers Table
CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    address TEXT DEFAULT '',
    active INTEGER DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS active INTEGER DEFAULT 1;
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_suppliers_shop ON suppliers (shop_id);

-- 4. Menu Items / Products Table
CREATE TABLE IF NOT EXISTS menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    price_cents BIGINT NOT NULL DEFAULT 0,
    cost_cents BIGINT DEFAULT 0,
    wholesale_price_cents BIGINT DEFAULT 0,
    stock_qty NUMERIC DEFAULT 0,
    reorder_level NUMERIC DEFAULT 5,
    sku TEXT DEFAULT '',
    barcode TEXT DEFAULT '',
    unit TEXT DEFAULT 'pcs',
    color TEXT DEFAULT '#334155',
    active INTEGER DEFAULT 1,
    batch_no TEXT DEFAULT '',
    expiry_date TEXT DEFAULT '',
    manufacturer TEXT DEFAULT '',
    strength TEXT DEFAULT '',
    variants_json TEXT DEFAULT '',
    decimal_qty_enabled INTEGER DEFAULT 0,
    image_url TEXT DEFAULT '',
    tax_code TEXT DEFAULT 'D',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS wholesale_price_cents BIGINT DEFAULT 0;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS reorder_level NUMERIC DEFAULT 5;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS tax_code TEXT DEFAULT 'D';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS batch_no TEXT DEFAULT '';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS expiry_date TEXT DEFAULT '';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS manufacturer TEXT DEFAULT '';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS strength TEXT DEFAULT '';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS variants_json TEXT DEFAULT '';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS decimal_qty_enabled INTEGER DEFAULT 0;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_menu_items_shop ON menu_items (shop_id);
CREATE INDEX IF NOT EXISTS idx_menu_items_sku ON menu_items (sku);
CREATE INDEX IF NOT EXISTS idx_menu_items_barcode ON menu_items (barcode);

-- 5. Customers Table
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    pin TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    address TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE customers ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS pin TEXT DEFAULT '';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS notes TEXT DEFAULT '';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_customers_shop ON customers (shop_id);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers (phone);

-- 6. Orders Table
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    ticket_no TEXT NOT NULL,
    order_type TEXT DEFAULT 'walk-in',
    customer_name TEXT DEFAULT 'Walk-In Customer',
    customer_kra_pin TEXT DEFAULT '',
    customer_phone TEXT DEFAULT '',
    customer_email TEXT DEFAULT '',
    customer_billing_address TEXT DEFAULT '',
    customer_remarks TEXT DEFAULT '',
    status TEXT DEFAULT 'paid',
    subtotal_cents BIGINT DEFAULT 0,
    discount_cents BIGINT DEFAULT 0,
    discount_type TEXT DEFAULT 'fixed',
    discount_value NUMERIC DEFAULT 0,
    tax_rate NUMERIC DEFAULT 0,
    tax_treatment TEXT DEFAULT 'non_vat',
    tax_cents BIGINT DEFAULT 0,
    total_cents BIGINT DEFAULT 0,
    paid_cents BIGINT DEFAULT 0,
    payment_method TEXT DEFAULT 'cash',
    payment_ref TEXT DEFAULT 'CASH',
    employee_name TEXT DEFAULT 'POS Terminal',
    table_name TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    etims_requested BOOLEAN DEFAULT FALSE,
    etims_status TEXT DEFAULT 'pending', -- 'pending', 'generated', 'review_required'
    cu_invoice_number TEXT DEFAULT '',
    scu_id TEXT DEFAULT '',
    receipt_signature TEXT DEFAULT '',
    internal_data TEXT DEFAULT '',
    qr_image TEXT DEFAULT '',
    invoice_number TEXT DEFAULT '',
    invoice_date TEXT DEFAULT '',
    fiscal_day_count TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_kra_pin TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_phone TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_email TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_billing_address TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_remarks TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_cents BIGINT DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_type TEXT DEFAULT 'fixed';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_value NUMERIC DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_rate NUMERIC DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_treatment TEXT DEFAULT 'non_vat';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS employee_name TEXT DEFAULT 'POS Terminal';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS table_name TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS notes TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS etims_requested BOOLEAN DEFAULT FALSE;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS etims_status TEXT DEFAULT 'pending';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS cu_invoice_number TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS scu_id TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS receipt_signature TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS internal_data TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS qr_image TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS invoice_number TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS invoice_date TEXT DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS fiscal_day_count TEXT DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_orders_shop ON orders (shop_id);
CREATE INDEX IF NOT EXISTS idx_orders_ticket_no ON orders (ticket_no);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders (created_at DESC);

-- 7. Order Line Items Table
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
    menu_item_id BIGINT,
    name TEXT NOT NULL,
    qty NUMERIC NOT NULL DEFAULT 1,
    unit_price_cents BIGINT NOT NULL DEFAULT 0,
    line_total_cents BIGINT NOT NULL DEFAULT 0,
    tax_code TEXT DEFAULT 'D',
    discount_amount_cents BIGINT DEFAULT 0,
    discount_rate NUMERIC DEFAULT 0,
    variant_info TEXT DEFAULT '',
    batch_no TEXT DEFAULT '',
    note TEXT DEFAULT ''
);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS tax_code TEXT DEFAULT 'D';
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS discount_amount_cents BIGINT DEFAULT 0;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS discount_rate NUMERIC DEFAULT 0;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS variant_info TEXT DEFAULT '';
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS batch_no TEXT DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items (order_id);

-- 8. eTIMS Queue Table (Cloud bridge for local invoice generator)
CREATE TABLE IF NOT EXISTS etims_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_hash TEXT DEFAULT '',
    shop_id TEXT NOT NULL DEFAULT 'retail',
    order_id BIGINT,
    ticket_no TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'processing', 'completed', 'failed'
    payload JSONB NOT NULL,
    result JSONB DEFAULT NULL,
    error TEXT DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE etims_queue ADD COLUMN IF NOT EXISTS job_hash TEXT DEFAULT '';
ALTER TABLE etims_queue ADD COLUMN IF NOT EXISTS shop_id TEXT NOT NULL DEFAULT 'retail';
CREATE INDEX IF NOT EXISTS idx_etims_queue_status ON etims_queue (shop_id, status);
CREATE INDEX IF NOT EXISTS idx_etims_queue_job_hash ON etims_queue (job_hash);

-- Enable Row Level Security (RLS) but allow anonymous access with API key for POS operation
ALTER TABLE shop_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE etims_queue ENABLE ROW LEVEL SECURITY;

-- Allow public read/write via Anon / Service Key (can be customized per your security requirements)
DO $$
BEGIN
    DROP POLICY IF EXISTS "Public Full Access Settings" ON shop_settings;
    CREATE POLICY "Public Full Access Settings" ON shop_settings FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Categories" ON categories;
    CREATE POLICY "Public Full Access Categories" ON categories FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Items" ON menu_items;
    CREATE POLICY "Public Full Access Items" ON menu_items FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Customers" ON customers;
    CREATE POLICY "Public Full Access Customers" ON customers FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Suppliers" ON suppliers;
    CREATE POLICY "Public Full Access Suppliers" ON suppliers FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Orders" ON orders;
    CREATE POLICY "Public Full Access Orders" ON orders FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access Order Items" ON order_items;
    CREATE POLICY "Public Full Access Order Items" ON order_items FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public Full Access eTIMS Queue" ON etims_queue;
    CREATE POLICY "Public Full Access eTIMS Queue" ON etims_queue FOR ALL USING (true) WITH CHECK (true);
END
$$;
