-- ==============================================================================
-- Oraforge Online POS - Dedicated Schema 'pos' Migration
-- Fully isolates the new POS from existing client tables in 'public'
-- ==============================================================================

CREATE SCHEMA IF NOT EXISTS pos;

GRANT USAGE ON SCHEMA pos TO postgres, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA pos GRANT ALL ON TABLES TO postgres, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA pos GRANT ALL ON SEQUENCES TO postgres, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA pos GRANT ALL ON FUNCTIONS TO postgres, anon, authenticated, service_role;

-- 1. Shop Settings Table
CREATE TABLE IF NOT EXISTS pos.shop_settings (
    shop_id TEXT PRIMARY KEY DEFAULT 'retail',
    business_name TEXT NOT NULL DEFAULT 'BuildMart Hardware',
    business_type TEXT NOT NULL DEFAULT 'hardware',
    kra_pin TEXT DEFAULT '',
    address TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    receipt_footer TEXT DEFAULT 'Thank you for your business!\n------- END OF RECEIPT -------',
    tax_rate NUMERIC DEFAULT 0,
    tax_rate_confirmed BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Categories Table
CREATE TABLE IF NOT EXISTS pos.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    sort_order INTEGER DEFAULT 0,
    business_type TEXT DEFAULT 'hardware',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_categories_shop ON pos.categories (shop_id);

-- 3. Suppliers Table
CREATE TABLE IF NOT EXISTS pos.suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    address TEXT DEFAULT '',
    active INTEGER DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_suppliers_shop ON pos.suppliers (shop_id);

-- 4. Menu Items / Products Table
CREATE TABLE IF NOT EXISTS pos.menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    category_id BIGINT REFERENCES pos.categories(id) ON DELETE SET NULL,
    supplier_id BIGINT REFERENCES pos.suppliers(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    price_cents BIGINT NOT NULL DEFAULT 0,
    cost_cents BIGINT DEFAULT 0,
    wholesale_price_cents BIGINT DEFAULT 0,
    stock_qty NUMERIC DEFAULT 0,
    reorder_level NUMERIC DEFAULT 5,
    sku TEXT DEFAULT '',
    barcode TEXT DEFAULT '',
    unit TEXT DEFAULT 'pcs',
    color TEXT DEFAULT '#334155',
    active INTEGER DEFAULT 1,
    batch_no TEXT DEFAULT '',
    expiry_date TEXT DEFAULT '',
    manufacturer TEXT DEFAULT '',
    strength TEXT DEFAULT '',
    variants_json TEXT DEFAULT '',
    decimal_qty_enabled INTEGER DEFAULT 0,
    image_url TEXT DEFAULT '',
    tax_code TEXT DEFAULT 'D',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_menu_items_shop ON pos.menu_items (shop_id);
CREATE INDEX IF NOT EXISTS idx_pos_menu_items_sku ON pos.menu_items (sku);
CREATE INDEX IF NOT EXISTS idx_pos_menu_items_barcode ON pos.menu_items (barcode);
CREATE INDEX IF NOT EXISTS idx_pos_menu_items_cat ON pos.menu_items (category_id);

-- 5. Customers Table
CREATE TABLE IF NOT EXISTS pos.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    name TEXT NOT NULL,
    pin TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    address TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_customers_shop ON pos.customers (shop_id);
CREATE INDEX IF NOT EXISTS idx_pos_customers_phone ON pos.customers (phone);

-- 6. Orders Table
CREATE TABLE IF NOT EXISTS pos.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id TEXT NOT NULL DEFAULT 'retail',
    ticket_no TEXT NOT NULL,
    supplier_id BIGINT,
    order_type TEXT DEFAULT 'walk-in',
    customer_name TEXT DEFAULT 'Walk-In Customer',
    customer_kra_pin TEXT DEFAULT '',
    customer_phone TEXT DEFAULT '',
    customer_email TEXT DEFAULT '',
    customer_billing_address TEXT DEFAULT '',
    customer_remarks TEXT DEFAULT '',
    status TEXT DEFAULT 'paid',
    subtotal_cents BIGINT DEFAULT 0,
    discount_cents BIGINT DEFAULT 0,
    discount_type TEXT DEFAULT 'fixed',
    discount_value NUMERIC DEFAULT 0,
    tax_rate NUMERIC DEFAULT 0,
    tax_treatment TEXT DEFAULT 'non_vat',
    tax_cents BIGINT DEFAULT 0,
    total_cents BIGINT DEFAULT 0,
    paid_cents BIGINT DEFAULT 0,
    payment_method TEXT DEFAULT 'cash',
    payment_ref TEXT DEFAULT 'CASH',
    created_by INTEGER DEFAULT 1,
    employee_name TEXT DEFAULT 'POS Terminal',
    table_name TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    etims_requested BOOLEAN DEFAULT FALSE,
    etims_status TEXT DEFAULT 'pending',
    cu_invoice_number TEXT DEFAULT '',
    scu_id TEXT DEFAULT '',
    receipt_signature TEXT DEFAULT '',
    internal_data TEXT DEFAULT '',
    qr_image TEXT DEFAULT '',
    invoice_number TEXT DEFAULT '',
    invoice_date TEXT DEFAULT '',
    fiscal_day_count TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_orders_shop ON pos.orders (shop_id);
CREATE INDEX IF NOT EXISTS idx_pos_orders_ticket_no ON pos.orders (ticket_no);
CREATE INDEX IF NOT EXISTS idx_pos_orders_created_at ON pos.orders (created_at DESC);

-- 7. Order Line Items Table
CREATE TABLE IF NOT EXISTS pos.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES pos.orders(id) ON DELETE CASCADE,
    menu_item_id BIGINT,
    name TEXT NOT NULL,
    qty NUMERIC NOT NULL DEFAULT 1,
    unit_price_cents BIGINT NOT NULL DEFAULT 0,
    line_total_cents BIGINT NOT NULL DEFAULT 0,
    tax_code TEXT DEFAULT 'D',
    discount_amount_cents BIGINT DEFAULT 0,
    discount_rate NUMERIC DEFAULT 0,
    variant_info TEXT DEFAULT '',
    batch_no TEXT DEFAULT '',
    note TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_pos_order_items_order_id ON pos.order_items (order_id);

-- 8. eTIMS Queue Table
CREATE TABLE IF NOT EXISTS pos.etims_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_hash TEXT DEFAULT '',
    shop_id TEXT NOT NULL DEFAULT 'retail',
    order_id BIGINT,
    ticket_no TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    payload JSONB NOT NULL,
    result JSONB DEFAULT NULL,
    error TEXT DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pos_etims_queue_status ON pos.etims_queue (shop_id, status);
CREATE INDEX IF NOT EXISTS idx_pos_etims_queue_job_hash ON pos.etims_queue (job_hash);

-- Grants
GRANT ALL ON ALL TABLES IN SCHEMA pos TO postgres, anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA pos TO postgres, anon, authenticated, service_role;

-- Enable Row Level Security (RLS)
ALTER TABLE pos.shop_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos.etims_queue ENABLE ROW LEVEL SECURITY;

-- Allow read/write access via API keys
DO $$
BEGIN
    DROP POLICY IF EXISTS "POS Full Access Settings" ON pos.shop_settings;
    CREATE POLICY "POS Full Access Settings" ON pos.shop_settings FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Categories" ON pos.categories;
    CREATE POLICY "POS Full Access Categories" ON pos.categories FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Suppliers" ON pos.suppliers;
    CREATE POLICY "POS Full Access Suppliers" ON pos.suppliers FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Items" ON pos.menu_items;
    CREATE POLICY "POS Full Access Items" ON pos.menu_items FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Customers" ON pos.customers;
    CREATE POLICY "POS Full Access Customers" ON pos.customers FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Orders" ON pos.orders;
    CREATE POLICY "POS Full Access Orders" ON pos.orders FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Order Items" ON pos.order_items;
    CREATE POLICY "POS Full Access Order Items" ON pos.order_items FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "POS Full Access Queue" ON pos.etims_queue;
    CREATE POLICY "POS Full Access Queue" ON pos.etims_queue FOR ALL USING (true) WITH CHECK (true);
END
$$;
